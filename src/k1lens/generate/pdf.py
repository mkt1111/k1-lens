"""Render a Schedule K-1 facsimile to PDF.

The page is a labeled text form, not a reproduction of the IRS artwork.
Clean and rotated variants keep a text layer. The rasterized variant is an
image of that form, slightly skewed, with no text layer.
"""

from __future__ import annotations

import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from reportlab.lib.colors import black
from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen.canvas import Canvas

from k1lens.domain.access import get_coded, get_extracted
from k1lens.domain.fields import CODED_BY_PATH, SCALAR_BY_PATH, FieldKind
from k1lens.domain.models import ScheduleK1
from k1lens.domain.parsing import format_value
from k1lens.generate.build import Variant

PAGE_W, PAGE_H = letter
_MARGIN_X = 0.65 * inch
_TOP = PAGE_H - 0.55 * inch
_BOTTOM = 0.55 * inch
_LEADING = 11

# Part III reading order, mixing scalar paths and coded boxes.
_PART_III_ORDER: tuple[str, ...] = (
    "part_iii.ordinary_business_income",
    "part_iii.net_rental_real_estate",
    "part_iii.other_net_rental",
    "part_iii.guaranteed_payments_services",
    "part_iii.guaranteed_payments_capital",
    "part_iii.guaranteed_payments_total",
    "part_iii.interest_income",
    "part_iii.ordinary_dividends",
    "part_iii.qualified_dividends",
    "part_iii.dividend_equivalents",
    "part_iii.royalties",
    "part_iii.net_short_term_capital_gain",
    "part_iii.net_long_term_capital_gain",
    "part_iii.collectibles_gain",
    "part_iii.unrecaptured_1250_gain",
    "part_iii.net_section_1231_gain",
    "coded:part_iii.other_income",
    "part_iii.section_179_deduction",
    "coded:part_iii.other_deductions",
    "coded:part_iii.self_employment",
    "coded:part_iii.credits",
    "part_iii.schedule_k3_attached",
    "coded:part_iii.amt_items",
    "coded:part_iii.tax_exempt_and_nondeductible",
    "coded:part_iii.distributions",
    "coded:part_iii.other_information",
    "part_iii.foreign_taxes_paid",
)


def render_pdf(doc: ScheduleK1, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    variant = doc.variant
    if variant == Variant.RASTERIZED.value:
        with tempfile.TemporaryDirectory() as tmp:
            vector = Path(tmp) / "vector.pdf"
            _write_vector(doc, vector, rotate=False)
            _rasterize(vector, dest, skew_degrees=0.8)
        return
    _write_vector(doc, dest, rotate=variant == Variant.ROTATED.value)


def _write_vector(doc: ScheduleK1, dest: Path, *, rotate: bool) -> None:
    canvas = Canvas(str(dest), pagesize=letter, invariant=1)
    canvas.setTitle(f"{doc.document_id} synthetic Schedule K-1")
    canvas.setAuthor("K1-Lens synthetic generator")
    for page_lines in _pages(doc):
        _draw_page(canvas, page_lines, rotate=rotate)
        canvas.showPage()
    canvas.save()


def _pages(doc: ScheduleK1) -> list[list[str]]:
    header = [
        "SYNTHETIC SAMPLE - NOT A FILED TAX RETURN",
        "SCHEDULE K-1 (FORM 1065)",
        "Partner's Share of Income, Deductions, Credits, etc.",
        f"TAX YEAR: {doc.tax_year if doc.tax_year is not None else ''}",
        f"DOCUMENT ID: {doc.document_id}",
        f"VARIANT: {doc.variant}",
        "All names, EINs, and amounts are fictitious.",
        "",
        "PART I - INFORMATION ABOUT THE PARTNERSHIP",
    ]
    page_one = (
        header + _section_lines(doc, "Part I") + ["", "PART II - INFORMATION ABOUT THE PARTNER"]
    )
    page_one += _section_lines(doc, "Part II", skip={"part_ii.contributed_builtin_gain"})
    page_one += ["", "ITEM L - PARTNER'S CAPITAL ACCOUNT ANALYSIS"]
    page_one += _section_lines(doc, "Capital account")
    builtin = _scalar_line(doc, "part_ii.contributed_builtin_gain")
    if builtin is not None:
        page_one += ["", builtin]
    page_two = [
        "PART III - PARTNER'S SHARE OF CURRENT YEAR INCOME, DEDUCTIONS, CREDITS, AND OTHER ITEMS",
        *_part_iii_lines(doc),
        "",
        "Generated by K1-Lens. Synthetic data only. Not a filed return.",
    ]
    return [page_one, page_two]


def _section_lines(doc: ScheduleK1, section: str, skip: set[str] | None = None) -> list[str]:
    skipped = skip or set()
    lines: list[str] = []
    for spec in SCALAR_BY_PATH.values():
        if spec.section != section or spec.path in skipped:
            continue
        line = _scalar_line(doc, spec.path)
        if line is not None:
            lines.append(line)
    return lines


def _part_iii_lines(doc: ScheduleK1) -> list[str]:
    lines: list[str] = []
    for token in _PART_III_ORDER:
        if token.startswith("coded:"):
            path = token.removeprefix("coded:")
            spec = CODED_BY_PATH[path]
            for item in get_coded(doc, path):
                amount = item.amount.value
                if amount is None:
                    continue
                lines.append(
                    f"{spec.pdf_prefix} {item.code}: {format_value(FieldKind.MONEY, amount)}"
                )
            continue
        line = _scalar_line(doc, token)
        if line is not None:
            lines.append(line)
    return lines


def _scalar_line(doc: ScheduleK1, path: str) -> str | None:
    spec = SCALAR_BY_PATH[path]
    value = get_extracted(doc, path).value
    if value is None:
        return None
    return f"{spec.pdf_label}: {format_value(spec.kind, value)}"


def _draw_page(canvas: Canvas, lines: list[str], *, rotate: bool) -> None:
    canvas.saveState()
    if rotate:
        canvas.translate(PAGE_W / 2, PAGE_H / 2)
        canvas.rotate(1.2)
        canvas.translate(-PAGE_W / 2, -PAGE_H / 2)
    _watermark(canvas)
    y = _TOP
    for line in lines:
        if y < _BOTTOM:
            break
        if line == "":
            y -= _LEADING * 0.6
            continue
        if line.startswith("SYNTHETIC SAMPLE") or (
            line.startswith("SCHEDULE K-1") or line.startswith("PART ") or line.startswith("ITEM L")
        ):
            canvas.setFont("Helvetica-Bold", 9)
        else:
            canvas.setFont("Helvetica", 8)
        canvas.setFillColor(black)
        canvas.drawString(_MARGIN_X, y, line)
        y -= _LEADING
    canvas.restoreState()


_WATERMARK: Image.Image | None = None


def draw_sample_watermark(canvas: Canvas) -> None:
    """Draw SAMPLE as an image so the word cannot leak into the text layer."""

    _watermark(canvas)


def _watermark(canvas: Canvas) -> None:
    """Draw SAMPLE as an image so it cannot leak into the text layer."""

    image = _watermark_image()
    width = 420
    height = width * image.height / image.width
    canvas.drawImage(
        ImageReader(image),
        (PAGE_W - width) / 2,
        (PAGE_H - height) / 2,
        width=width,
        height=height,
        mask="auto",
    )


def _watermark_image() -> Image.Image:
    global _WATERMARK
    if _WATERMARK is None:
        image = Image.new("RGBA", (640, 140), (255, 255, 255, 0))
        draw = ImageDraw.Draw(image)
        font = ImageFont.load_default(size=96)
        draw.text((10, 20), "SAMPLE", fill=(210, 210, 210, 255), font=font)
        _WATERMARK = image.rotate(32, expand=True, resample=Image.Resampling.BICUBIC)
    return _WATERMARK


def _rasterize(src: Path, dest: Path, *, skew_degrees: float) -> None:
    import pypdfium2 as pdfium

    pdf = pdfium.PdfDocument(str(src))
    images: list[Image.Image] = []
    try:
        scale = 140 / 72
        for index in range(len(pdf)):
            page = pdf[index]
            bitmap = page.render(scale=scale)
            image = bitmap.to_pil().convert("RGB")
            if skew_degrees:
                image = image.rotate(
                    skew_degrees,
                    expand=True,
                    fillcolor=(255, 255, 255),
                    resample=Image.Resampling.BICUBIC,
                )
            images.append(image)
    finally:
        pdf.close()

    canvas = Canvas(str(dest), pagesize=letter, invariant=1)
    canvas.setTitle("synthetic Schedule K-1 scan")
    canvas.setAuthor("K1-Lens synthetic generator")
    for image in images:
        canvas.drawImage(
            ImageReader(image),
            0,
            0,
            width=PAGE_W,
            height=PAGE_H,
            preserveAspectRatio=True,
            anchor="c",
            mask="auto",
        )
        canvas.showPage()
    canvas.save()
